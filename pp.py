import csv


def read_employees(path: str) -> list[dict]:
    """
        Считать данные о сотрудниках в list[dict]  - где dict - словарь о каждом сотрулнике
    """
    with open(path) as f:
        lines = f.readlines()
    header = lines[0].strip().split(",")
    return [dict(zip(header, line.strip().split(","))) for line in lines[1:]]

def sort_by_salary(employees:list[dict]) -> list[dict]:
    """
        Отсортировать список сотрудников по зарплате
    """
    return sorted(employees, key=lambda x: int(x['salary']), reverse=True) #в задании не уточнено по возр или по убыв

def print_table(employees: list[dict]) -> None:
    """
        Вывести список сотрудников в виде таблицы с выровненными колонками
    """
    if not employees:
        print("Нет данных")
        return
    headers = list(employees[0].keys())  # названия колонок из первого словаря (ключи у всех одинаковые)
    widths = {h: max(len(h), max(len(e[h]) for e in employees)) for h in headers}  # ширина колонки = макс(длина заголовка, длина самого длинного значения)
    print(" | ".join(h.ljust(widths[h]) for h in headers))  # шапка таблицы, выравнивание по левому краю
    print("-+-".join("-" * widths[h] for h in headers))  # линия-разделитель под шапкой
    for e in employees:
        print(" | ".join(str(e[h]).ljust(widths[h]) for h in headers))  # строка данных с той же шириной, что и в шапке

employees = read_employees("employees.csv")
print_table(sort_by_salary(employees))

# Обоснование выбора структур данных

# list[dict] для хранения данных сотрудников:
# CSV — это таблица: набор однотипных строк, и list естественно хранит такую
# последовательность, сохраняя порядок строк файла и давая доступ по индексу.
# Каждая строка (сотрудник) — это набор именованных полей (id, name, department,
# salary и т.д.), а dict хранит пары "имя поля — значение", то есть даёт доступ
# к данным по названию колонки, а не по номеру. Это и безопаснее (не собьётся
# при смене порядка колонок), и читаемее — например, ['salary'] понятнее, чем
# e[6]. Комбинация list[dict] прямо отражает структуру CSV: список — это файл,
# каждый dict внутри — одна строка. Такое представление легко расширять и
# обрабатывать стандартными средствами Python (циклы, comprehension, sorted)
# без сторонних библиотек.

# list для сортировки по зарплате:
# Сортировка — это перестановка уже существующих элементов коллекции с
# сохранением их полного набора, а list — единственная из базовых структур
# Python, где вообще определён и важен порядок элементов, поэтому она для этой
# операции естественна. set для сортировки не подходит — не хранит порядок и
# не допускает дубликаты, а зарплаты могут совпадать. dict тоже не про порядок
# элементов, а про доступ по ключу; tuple неизменяем, и создавать новый кортеж
# на каждую перестановку было бы избыточно. sorted(employees, key=lambda x:
# int(x['salary']), reverse=True) возвращает новый list, отсортированный по
# зарплате, не изменяя исходный — это удобно, если исходный порядок сотрудников
# ещё понадобится. Таким образом выбор list продиктован природой самой задачи:
# сортировка — это операция над последовательностью, а list эту
# последовательность и представляет.
